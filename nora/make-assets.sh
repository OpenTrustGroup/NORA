# Make NORA's release assets, the binary parts of the build that are not
# kept in git, from where their makers publish them. Nothing comes from
# another product's release. Run in a NORA checkout after `jiri update`:
#
#   nora/make-assets.sh OUT_DIR [--linaro FILE]
#
# OUT_DIR gets the tarballs and ASSETS.sha256 for them; publish them as a
# release of the NORA repository and copy ASSETS.sha256 over
# nora/ASSETS.sha256 (setting ASSETS_RELEASE). Each tarball unpacks at the
# checkout's root, which nora/fetch-assets.sh does:
#
#   nora-zircon-toolchains-linux-x64.tar.xz
#       zircon/prebuilt/: the toolchains zircon/prebuilt/zircon.versions
#       pins, from Fuchsia's storage (zircon/scripts/download-prebuilt).
#   nora-buildtools-linux-x64.tar.xz
#       buildtools/linux-x64/: clang, gn, ninja, go, godepfile and the host
#       sysroot nora/buildtools.ensure pins, from CIPD.
#   nora-gcc-linaro-7.5.0-2019.12.tar.xz
#       prebuilts/gcc-linaro-7.5.0-2019.12/: Linaro's GCC 7.5-2019.12 for
#       aarch64 Linux, which builds linux. Linaro no longer serves its old
#       releases; the file is checked against its SHA-256 (LINARO_SHA256),
#       from --linaro, or else from a mirror (LINARO_URL).
#   nora-bazel.tar.xz
#       out/nora-bazel/: bazel 4.0.0 from bazel's releases, and the
#       repository cache of what the REE and host workspaces download, each
#       file pinned by its SHA-256 in the workspaces' rules.
#   nora-qemu-subprojects.tar.xz
#       third_party/qemu/subprojects/: the subprojects QEMU's meson wraps
#       pin, from their git repositories at the pinned revisions.
#
# The bazel workspaces refer to the build's outputs, so run this in a
# checkout nora/build.sh has built (with the previous assets, or with
# ones made by hand); the other assets need only the sources.
#
# The tarballs are packed deterministically: making them again from the
# same pins gives the same files.

set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
LINARO_NAME=gcc-linaro-7.5.0-2019.12-x86_64_aarch64-linux-gnu.tar.xz
LINARO_SHA256=3b6465fb91564b54bbdf9578b4cc3aa198dd363f7a43820eab06ea2932c8e0bf
LINARO_URL="https://huggingface.co/csukuangfj/sherpa-ncnn-toolchains/resolve/main/$LINARO_NAME"
BAZEL_VERSION=4.0.0
BAZEL_SHA256=7bee349a626281fc8b8d04a7a0b0358492712377400ab12533aeb39c2eb2b901
QEMU_SUBPROJECTS="berkeley-softfloat-3 berkeley-testfloat-3 dtc keycodemapdb"

[ $# -ge 1 ] || { echo "usage: $0 OUT_DIR [--linaro FILE]" >&2; exit 1; }
OUT=$(realpath -m "$1"); shift
LINARO_FILE=
while [ $# -gt 0 ]; do
  case $1 in
    --linaro) LINARO_FILE=$(realpath "$2"); shift 2 ;;
    *) echo "unknown option: $1" >&2; exit 1 ;;
  esac
done
mkdir -p "$OUT"
W=$(mktemp -d "$OUT/.work.XXXXXX")
trap 'rm -rf "$W"' EXIT

# pack NAME DIR PATH...: a tarball of PATH... under DIR, the same bytes for
# the same files
pack() {
  local name=$1 dir=$2; shift 2
  echo "packing $name"
  tar -C "$dir" --sort=name --mtime=@0 --owner=0 --group=0 --numeric-owner \
      --format=gnu -cf - "$@" | xz -T1 -6 > "$OUT/$name"
}

# Zircon's toolchains: download-prebuilt fills zircon/prebuilt/downloads
# from storage.googleapis.com/fuchsia, as the pins in zircon.versions say.
echo "== zircon toolchains"
mkdir -p "$W/z/zircon/scripts" "$W/z/zircon/prebuilt"
cp "$ROOT/zircon/scripts/download-prebuilt" "$W/z/zircon/scripts/"
cp "$ROOT/zircon/prebuilt/zircon.ensure" "$ROOT/zircon/prebuilt/zircon.versions" \
   "$W/z/zircon/prebuilt/"
"$W/z/zircon/scripts/download-prebuilt" > "$W/z.log" 2>&1 ||
  { tail -20 "$W/z.log" >&2; exit 1; }
rm -f "$W"/z/zircon/prebuilt/downloads/*.zip
# config.mk names the script that wrote it by its path: make it the path
# in a checkout.
sed -i '1s|^# Generated by .*download-prebuilt|# Generated by scripts/download-prebuilt|' \
  "$W/z/zircon/prebuilt/config.mk"
pack nora-zircon-toolchains-linux-x64.tar.xz "$W/z" \
  zircon/prebuilt/config.mk zircon/prebuilt/downloads

# buildtools from CIPD, with the client buildtools/cipd fetches.
echo "== buildtools"
mkdir -p "$W/b/buildtools"
"$ROOT/buildtools/cipd" ensure -ensure-file "$ROOT/nora/buildtools.ensure" \
  -root "$W/b/buildtools/linux-x64" -log-level warning
# The Fuchsia build puts clang.stamp's first line into every compile line,
# so that a new clang rebuilds everything: the clang pin.
sed -n 's|^fuchsia/clang/${platform} git_revision:||p' "$ROOT/nora/buildtools.ensure" \
  > "$W/b/buildtools/linux-x64/clang.stamp"
[ -s "$W/b/buildtools/linux-x64/clang.stamp" ]
pack nora-buildtools-linux-x64.tar.xz "$W/b" buildtools/linux-x64

# Linaro's GCC, renamed to the directory the build expects.
echo "== gcc-linaro"
if [ -z "$LINARO_FILE" ]; then
  LINARO_FILE="$W/$LINARO_NAME"
  curl -fL -o "$LINARO_FILE" "$LINARO_URL"
fi
echo "$LINARO_SHA256  $LINARO_FILE" | sha256sum -c --quiet
mkdir -p "$W/l/prebuilts"
tar -xJf "$LINARO_FILE" -C "$W/l/prebuilts"
mv "$W/l/prebuilts/${LINARO_NAME%.tar.xz}" "$W/l/prebuilts/gcc-linaro-7.5.0-2019.12"
pack nora-gcc-linaro-7.5.0-2019.12.tar.xz "$W/l" prebuilts/gcc-linaro-7.5.0-2019.12

# bazel and its repository cache: analysing the targets nora/build.sh
# builds, in fresh output bases with an empty cache, downloads every
# archive the workspaces pin.
echo "== bazel"
B="$W/bz/out/nora-bazel"
mkdir -p "$B/bazelisk/bin/bazelbuild"
curl -fL -o "$B/bazelisk/bin/bazelbuild/bazel-$BAZEL_VERSION-linux-x86_64" \
  "https://releases.bazel.build/$BAZEL_VERSION/release/bazel-$BAZEL_VERSION-linux-x86_64"
echo "$BAZEL_SHA256  $B/bazelisk/bin/bazelbuild/bazel-$BAZEL_VERSION-linux-x86_64" |
  sha256sum -c --quiet
chmod 755 "$B/bazelisk/bin/bazelbuild/bazel-$BAZEL_VERSION-linux-x86_64"
(
  set +u
  cd "$ROOT"
  unset FUCHSIA_DIR FUCHSIA_CONFIG FUCHSIA_OUT_DIR FUCHSIA_BUILD_DIR
  source scripts/env.sh >/dev/null 2>&1
  source scripts/devshell/lib/vars.sh
  source buildtools/vars.sh
  fx-config-read
  FUCHSIA_DIR="$ROOT" source build/bazel_symlink.sh
  python3 nora/qemu/adapt-bazel.py "$ROOT"
  export BAZELISK_HOME="$B/bazelisk"
  for ws in ree host; do
    case $ws in
      ree) targets=(--config=linux_6.6 //:linux-image-6.6 //:linux-rootfs) ;;
      host) targets=(//:qemu //:soc_term) ;;
    esac
    (cd "bazel/$ws" &&
     bazelisk --output_base="$W/ob-$ws" build --nobuild \
       --repository_cache="$B/repos" "${targets[@]}" &&
     bazelisk --output_base="$W/ob-$ws" shutdown)
  done
) > "$W/bazel.log" 2>&1 || { tail -20 "$W/bazel.log" >&2; exit 1; }
pack nora-bazel.tar.xz "$W/bz" out/nora-bazel

# QEMU's subprojects, as `meson subprojects download` makes them: each wrap's
# repository at its revision, with the wrap's patch directory over it.
echo "== qemu subprojects"
S="$W/q/third_party/qemu/subprojects"
mkdir -p "$S"
for s in $QEMU_SUBPROJECTS; do
  wrap="$ROOT/third_party/qemu/subprojects/$s.wrap"
  url=$(sed -n 's/^url *= *//p' "$wrap")
  rev=$(sed -n 's/^revision *= *//p' "$wrap")
  patch=$(sed -n 's/^patch_directory *= *//p' "$wrap")
  git init -q "$S/$s"
  git -C "$S/$s" fetch -q --depth 1 "$url" "$rev"
  git -C "$S/$s" checkout -q FETCH_HEAD
  rm -rf "$S/$s/.git"
  if [ -n "$patch" ]; then
    cp -r "$ROOT/third_party/qemu/subprojects/packagefiles/$patch/." "$S/$s/"
  fi
  sha256sum < "$wrap" | cut -c1-64 > "$S/$s/.meson-subproject-wrap-hash.txt"
done
pack nora-qemu-subprojects.tar.xz "$W/q" third_party/qemu/subprojects

(cd "$OUT" && sha256sum nora-*.tar.xz) > "$OUT/ASSETS.sha256"
echo "assets in $OUT:"
cat "$OUT/ASSETS.sha256"
